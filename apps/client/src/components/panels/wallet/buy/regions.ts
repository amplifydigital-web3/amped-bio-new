let names: Intl.DisplayNames | null = null;

export function countryName(code: string): string {
  try {
    names ??= new Intl.DisplayNames(["en"], { type: "region" });
    return names.of(code) ?? code;
  } catch {
    return code;
  }
}

export function stateName(code: string): string {
  return US_STATES[code] ?? code;
}

export function regionLabel(region: { country: string; subdivision: string | null }): string {
  if (region.country === "US" && region.subdivision) return `${stateName(region.subdivision)}, US`;
  return countryName(region.country);
}
